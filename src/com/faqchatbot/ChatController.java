    // FEATURE 8: Animated gradient strip
    // ═════════════════════════════════════════════════════════════════════════
    private void animateGradientStrip() {
        // We animate by shifting a CSS-class-driven background-position
        // using a CSS keyframe animation defined in style.css (added below).
        // As a fallback, we also set a JavaFX animated Rectangle fill.
        Rectangle bar = new Rectangle();
        bar.setHeight(3);
        bar.widthProperty().bind(gradientStrip.widthProperty());

        Stop[] stops = {
            new Stop(0.0, Color.web("#1f6feb")),
            new Stop(0.3, Color.web("#a371f7")),
            new Stop(0.6, Color.web("#3fb950")),
            new Stop(1.0, Color.web("#1f6feb"))
        };
        LinearGradient gradient = new LinearGradient(0, 0, 1, 0, true,
                CycleMethod.REFLECT, stops);
        bar.setFill(gradient);
        gradientStrip.getChildren().add(bar);

        // Animate gradient offset by moving the bar left/right
        TranslateTransition tt = new TranslateTransition(Duration.seconds(3), bar);
        tt.setFromX(0);
        tt.setToX(-200);
        tt.setCycleCount(Animation.INDEFINITE);
        tt.setAutoReverse(true);
        tt.play();
    }

    // ═════════════════════════════════════════════════════════════════════════
    // FEATURE 10: Global keyboard shortcuts
    // ═════════════════════════════════════════════════════════════════════════
    private void registerGlobalShortcuts() {
        // Called after the node is added to the scene; we add listener lazily
        this.sceneProperty().addListener((obs, ov, scene) -> {
            if (scene == null) return;
            scene.addEventFilter(KeyEvent.KEY_PRESSED, e -> {
                if (e.isControlDown()) {
                    switch (e.getCode()) {
                        case F -> { e.consume(); openSearch(); }
                        case N -> { e.consume(); clearChat(); }
                        case P -> { e.consume(); new PinnedPanel().show(); }
                        case COMMA -> { e.consume(); openSettings(); }
                        case SLASH -> { e.consume(); new KeyboardShortcutsPanel().show(); }
                        case E -> { e.consume(); showExportMenu(); }
                        case L -> { e.consume(); clearChat(); }
                        case R -> { e.consume(); regenerateResponse(); }
                        case M -> { e.consume(); toggleMic(); }
                        case S -> { e.consume(); toggleNotifSound(); }
                        case T -> {
                            e.consume();
                            SpeechManager.setEnabled(!SpeechManager.isEnabled());
                        }
                        // Language switch – Feature 9
                        case DIGIT1 -> { e.consume(); switchLanguage(I18nManager.Language.ENGLISH); }
                        case DIGIT2 -> { e.consume(); switchLanguage(I18nManager.Language.ARABIC); }
                        case DIGIT3 -> { e.consume(); switchLanguage(I18nManager.Language.URDU); }
                        case DIGIT4 -> { e.consume(); switchLanguage(I18nManager.Language.FRENCH); }
                        default -> {}
                    }
                } else if (e.getCode() == KeyCode.ESCAPE) {
                    if (micRecording) { e.consume(); toggleMic(); }
                }
            });
        });
    }

    // ═════════════════════════════════════════════════════════════════════════
    // FEATURE 1: Voice Input
    // ═════════════════════════════════════════════════════════════════════════
    private void toggleMic() {
        if (!VoiceInputManager.isAvailable()) return;

        if (!micRecording) {
            boolean started = VoiceInputManager.startRecording();
            if (started) {
                micRecording = true;
                micButton.setText(I18nManager.t("btn.mic.stop"));
                micButton.getStyleClass().add("mic-recording");
                statusLabel.setText("🔴 Recording…");
            }
        } else {
            micRecording = false;
            micButton.setText(I18nManager.t("btn.mic"));
            micButton.getStyleClass().remove("mic-recording");
            statusLabel.setText("Transcribing…");
            VoiceInputManager.stopRecording(text -> Platform.runLater(() -> {
                statusLabel.setText(I18nManager.t("header.online"));
                if (!text.startsWith("⚠️")) {
                    inputField.setText(text);
                    inputField.positionCaret(text.length());
                } else {
                    showAlert("Voice Error", text);
                }
            }));
        }
    }

