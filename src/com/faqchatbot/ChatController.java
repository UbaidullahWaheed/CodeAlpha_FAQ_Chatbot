    // REMAINING ORIGINAL METHODS (enhanced)
    // ═════════════════════════════════════════════════════════════════════════
    private void regenerateResponse() {
        setInputDisabled(true);
        statusLabel.setText(I18nManager.t("header.regen"));

        Label typingLabel = new Label(I18nManager.t("typing.regen"));
        typingLabel.getStyleClass().add("typing-indicator");
        chatArea.getChildren().add(typingLabel);

        Thread thread = new Thread(() -> {
            String response = groqClient.regenerateLastResponse();
            Platform.runLater(() -> {
                chatArea.getChildren().remove(typingLabel);
                chatArea.getChildren().add(new ChatBubble(response, ChatBubble.BubbleType.BOT));
                setInputDisabled(false);
                statusLabel.setText(I18nManager.t("header.online"));
                NotificationSoundManager.ping(); // Feature 6
            });
        });
        thread.setDaemon(true);
        thread.start();
    }

    private void showExportMenu() {
        ContextMenu menu = new ContextMenu();
        MenuItem txtItem  = new MenuItem("📄 Export as TXT");
        MenuItem htmlItem = new MenuItem("🌐 Export as HTML");
        txtItem.setOnAction(e  -> FileHandler.exportAsTXT(currentSession, primaryStage));
        htmlItem.setOnAction(e -> FileHandler.exportAsHTML(currentSession, primaryStage));
        menu.getItems().addAll(txtItem, htmlItem);
        menu.show(exportButton, Side.BOTTOM, 0, 0);
    }

    private void openSettings() {
        SettingsPanel settings = new SettingsPanel(this, this.getScene());
        settings.show();
    }

    public void loadSession(ChatSession session) {
        this.currentSession = session;
        SessionManager.setCurrentSession(session);
        groqClient = new GroqClient();
        groqClient.setModel(session.getModel());
        groqClient.setPersona(session.getPersona());
        chatArea.getChildren().clear();
        for (ChatSession.Message msg : session.getMessages()) {
            ChatBubble.BubbleType t = msg.role.equals("user")
                    ? ChatBubble.BubbleType.USER : ChatBubble.BubbleType.BOT;
            chatArea.getChildren().add(new ChatBubble(msg.content, t));
        }
        updateModelLabel();
    }

    private void clearChat() {
        chatArea.getChildren().clear();
        currentSession = SessionManager.createNewSession();
        groqClient.clearHistory();
        if (sidebar != null) sidebar.refresh();
        showWelcomeMessage();
    }

    private void setInputDisabled(boolean disabled) {
        inputField.setDisable(disabled);
        sendButton.setDisable(disabled);
        clearButton.setDisable(disabled);
        uploadButton.setDisable(disabled);
        micButton.setDisable(disabled || !VoiceInputManager.isAvailable());
    }

    private void updateModelLabel() {
        modelLabel.setText("Model: " + groqClient.getCurrentModel()
                + "  ·  Persona: " + groqClient.getCurrentPersona());
    }

    // ── Helpers ───────────────────────────────────────────────────────────────
    private Button iconBtn(String icon, String tooltip, javafx.event.EventHandler<javafx.event.ActionEvent> handler) {
        Button btn = new Button(icon);
        btn.getStyleClass().add("header-icon-btn");
        btn.setTooltip(new Tooltip(tooltip));
        btn.setOnAction(handler);
        return btn;
    }

    /** Brief non-blocking toast notification in the status label. */
    private void showToast(String msg) {
        String prev = statusLabel.getText();
        statusLabel.setText(msg);
        PauseTransition pause = new PauseTransition(Duration.seconds(2));
        pause.setOnFinished(e -> statusLabel.setText(prev));
        pause.play();
    }

    private void showAlert(String title, String msg) {
        Alert alert = new Alert(Alert.AlertType.ERROR);
        alert.setTitle(title);
        alert.setContentText(msg);
        alert.show();
    }

