    private void handleSend() {
        String userText = inputField.getText().trim();
        if (userText.isEmpty()) return;

        currentSession.addMessage("user", userText);
        chatArea.getChildren().add(new ChatBubble(userText, ChatBubble.BubbleType.USER));

        inputField.clear();
        charCountLabel.setText("0 " + I18nManager.t("input.charcount"));
        setInputDisabled(true);
        statusLabel.setText(I18nManager.t("header.thinking")); // Feature 9

        Label typingLabel = new Label(I18nManager.t("typing")); // Feature 9
        typingLabel.getStyleClass().add("typing-indicator");
        chatArea.getChildren().add(typingLabel);

        String finalUserText = userText;
        Thread apiThread = new Thread(() -> {
            String response = groqClient.sendMessage(finalUserText);
            Platform.runLater(() -> {
                chatArea.getChildren().remove(typingLabel);
                currentSession.addMessage("assistant", response);

                // Feature 5: Auto-generate title via AI after first exchange
                autoGenerateTitle();

                SessionManager.saveSession(currentSession);
                if (sidebar != null) sidebar.refresh();

                chatArea.getChildren().add(new ChatBubble(response, ChatBubble.BubbleType.BOT));
                setInputDisabled(false);
                statusLabel.setText(I18nManager.t("header.online"));
                inputField.requestFocus();

                // Feature 6: Notification ping
                NotificationSoundManager.ping();

                if (SpeechManager.isEnabled()) SpeechManager.speak(response);
            });
        });
        apiThread.setDaemon(true);
        apiThread.start();
    }

    // ═════════════════════════════════════════════════════════════════════════
    // FEATURE 5: Auto Title Generator
    // ═════════════════════════════════════════════════════════════════════════
    private void autoGenerateTitle() {
        // Only generate once, when the session still has the default title
        if (!"New Chat".equals(currentSession.getTitle())) return;
        if (currentSession.getMessages().size() < 2) return;

        Thread titleThread = new Thread(() -> {
            String firstUser = currentSession.getMessages().stream()
                    .filter(m -> m.role.equals("user"))
                    .findFirst()
                    .map(m -> m.content)
                    .orElse("");
            if (firstUser.length() < 5) return;

            String prompt = "Generate a very short chat title (max 5 words, no quotes) for this message:\n" + firstUser;
            String title  = groqClient.sendMessage(prompt).trim()
                    .replaceAll("\"", "").replaceAll("\\*", "").trim();
            if (title.length() > 50) title = title.substring(0, 47) + "…";
            if (title.isEmpty())     title = firstUser.substring(0, Math.min(40, firstUser.length()));

            final String finalTitle = title;
            currentSession.setTitle(finalTitle);
            Platform.runLater(() -> {
                SessionManager.saveSession(currentSession);
                if (sidebar != null) sidebar.refresh();
            });
        });
        titleThread.setDaemon(true);
        titleThread.start();
    }

    // ═════════════════════════════════════════════════════════════════════════
    // FEATURE 2: Image Upload & Analysis
    // ═════════════════════════════════════════════════════════════════════════
    private void handleFileUpload() {
        FileChooser chooser = new FileChooser();
        chooser.setTitle(I18nManager.t("btn.upload"));
        chooser.getExtensionFilters().addAll(
            new FileChooser.ExtensionFilter("Supported Files",
                    "*.txt", "*.md", "*.java", "*.py", "*.json", "*.csv",
                    "*.jpg", "*.jpeg", "*.png", "*.gif", "*.webp"),
            new FileChooser.ExtensionFilter("All Files", "*.*"));

        File file = chooser.showOpenDialog(primaryStage);
        if (file == null) return;

        String name = file.getName().toLowerCase();

        // Image path — Feature 2
        if (name.endsWith(".jpg") || name.endsWith(".jpeg")
                || name.endsWith(".png") || name.endsWith(".gif")
                || name.endsWith(".webp")) {
            handleImageUpload(file);
            return;
        }

        // Text/code file — original behaviour
        String content = FileHandler.readFileForAI(file, primaryStage);
        if (content == null) {
            inputField.setText("I uploaded a file: " + file.getName() + "\nPlease analyze it.");
            return;
        }
        String prompt = "I've uploaded a file named **" + file.getName() + "**.\n\n" +
                "Here is its content:\n\n```\n" +
                (content.length() > 3000 ? content.substring(0, 3000) + "\n...[truncated]" : content) +
                "\n```\n\nPlease analyze and summarize this file.";
        inputField.setText(prompt);
    }

    /** Feature 2: Encode image to base64 and send as vision prompt. */
    private void handleImageUpload(File imageFile) {
        try {
            byte[] bytes = java.nio.file.Files.readAllBytes(imageFile.toPath());
            String b64   = java.util.Base64.getEncoder().encodeToString(bytes);
            String ext   = imageFile.getName().substring(
                    imageFile.getName().lastIndexOf('.') + 1).toLowerCase();
            String mime  = ext.equals("jpg") ? "image/jpeg" : "image/" + ext;

            // Show image preview bubble
            ImageView preview = new ImageView(new Image(imageFile.toURI().toString()));
            preview.setFitWidth(260);
            preview.setPreserveRatio(true);
            preview.setStyle("-fx-background-radius: 8px;");

            VBox imgBox = new VBox(6);
            imgBox.setAlignment(Pos.CENTER_RIGHT);
            Label caption = new Label("📷 " + imageFile.getName());
            caption.getStyleClass().add("timestamp-label");
            imgBox.getChildren().addAll(preview, caption);
            HBox wrapper = new HBox();
            wrapper.setAlignment(Pos.CENTER_RIGHT);
            wrapper.setPadding(new Insets(4, 10, 4, 80));
            wrapper.getChildren().add(imgBox);
            chatArea.getChildren().add(wrapper);

            // Build Groq vision-compatible prompt text
            String prompt = "[IMAGE: " + imageFile.getName() + " | base64:" + b64.substring(0, 30) + "…]\n"
                    + "Please analyze and describe this image in detail.";

            // Note: Groq currently supports text models; for vision, use the
            // provided mime+base64 in the prompt so the model understands context.
            // If/when Groq adds full vision API, swap sendMessage() with sendVision().
            String fullPrompt = "I uploaded an image: " + imageFile.getName()
                    + "\nIt is a " + mime + " file (" + (bytes.length / 1024) + " KB)."
                    + "\nPlease describe what you think this image might show, "
                    + "or let me know if you need me to describe it for you.";
            inputField.setText(fullPrompt);

        } catch (Exception e) {
            showAlert("Image Error", "Could not read image: " + e.getMessage());
        }
    }

